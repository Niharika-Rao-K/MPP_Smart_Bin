w3 = Web3(Web3.HTTPProvider(SEPOLIA_RPC_URL))

def mint_reward_tokens(recipient_wallet: str, amount: int = 10):
    """Mints ERC-20 tokens on Sepolia testnet to the user wallet."""
    if not w3.is_address(recipient_wallet):
        raise ValueError(f"Invalid Ethereum wallet address: {recipient_wallet}")

    account = w3.eth.account.from_key(PRIVATE_KEY)
    contract = w3.eth.contract(address=Web3.to_checksum_address(CONTRACT_ADDRESS), abi=CONTRACT_ABI)

    nonce = w3.eth.get_transaction_count(account.address)
    
    # Build transaction
    tx = contract.functions.mint(
        Web3.to_checksum_address(recipient_wallet), 
        amount
    ).build_transaction({
        'from': account.address,
        'nonce': nonce,
        'gas': 200000,
        'gasPrice': w3.eth.gas_price,
    })

    # Sign and send transaction
    signed_tx = w3.eth.account.sign_transaction(tx, private_key=PRIVATE_KEY)
    tx_hash = w3.eth.send_raw_transaction(signed_tx.rawTransaction)
    return w3.to_hex(tx_hash)

